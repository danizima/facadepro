import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtemp,mkdir,writeFile,readFile,readdir,rm,cp,lstat,symlink} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {randomUUID,createHash,createCipheriv} from 'node:crypto';
import {initializeRetention,purgeClosedLeads,retentionCandidates} from '../backend/retention.mjs';
import {createBackup,verifyBackup,restoreBackup,pruneBackups,maintenanceConfig} from '../backend/backups.mjs';

const temp=await mkdtemp(path.join(tmpdir(),'facade-data-safety13-'));
const data=path.join(temp,'data'),now=new Date('2026-09-27T04:00:00.000Z');
let db,restored;
try {
  await mkdir(data,{mode:0o700});for(const folder of ['uploads','media','materials'])await mkdir(path.join(data,folder));
  const secret='ab'.repeat(48);await writeFile(path.join(data,'secret'),secret,{mode:0o600});
  db=new DatabaseSync(path.join(data,'facadepro.sqlite'));
  db.exec(`PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON;
    CREATE TABLE leads(id TEXT PRIMARY KEY,created TEXT,status TEXT,revision INTEGER,next_contact TEXT);
    CREATE TABLE files(id TEXT PRIMARY KEY,lead_id TEXT REFERENCES leads(id) ON DELETE CASCADE,size INTEGER);
    CREATE TABLE content(id INTEGER PRIMARY KEY,json TEXT);
    CREATE TABLE notification_settings(id INTEGER PRIMARY KEY,sealed TEXT);
    CREATE TABLE admins(username TEXT PRIMARY KEY,password TEXT);
    CREATE TABLE outbox(id TEXT PRIMARY KEY,lead_id TEXT REFERENCES leads(id) ON DELETE CASCADE,state TEXT);
    INSERT INTO leads VALUES('legacy-closed','2020-01-01T00:00:00.000Z','closed',1,'');`);
  initializeRetention(db,now);
  assert.equal(db.prepare("SELECT closed_at FROM leads WHERE id='legacy-closed'").get().closed_at,now.toISOString(),'migration gives old closed leads a full new grace period');
  initializeRetention(db,new Date('2026-10-01T00:00:00Z'));
  assert.equal(db.prepare("SELECT closed_at FROM leads WHERE id='legacy-closed'").get().closed_at,now.toISOString(),'migration is idempotent');
  const add=(id,status,closed='',next='')=>db.prepare('INSERT INTO leads VALUES(?,?,?,?,?,?)').run(id,'2020-01-01T00:00:00.000Z',status,1,next,closed);
  for(const status of ['new','review','estimate','sent','won'])add(status,status);
  add('expired','closed','2025-01-01T00:00:00.000Z');
  add('future-contact','closed','2025-01-01T00:00:00.000Z','2026-12-01');
  add('recently-closed','closed','2026-09-26T00:00:00.000Z');
  add('reopened','closed','2025-01-01T00:00:00.000Z');
  db.prepare("UPDATE leads SET status='review' WHERE id='reopened'").run();
  assert.equal(db.prepare("SELECT closed_at FROM leads WHERE id='reopened'").get().closed_at,'');
  assert.deepEqual(retentionCandidates(db,now).map(x=>x.id),['expired']);
  const fileId=randomUUID(),attachment=Buffer.from('private attachment from uncheckpointed WAL');
  db.prepare('INSERT INTO files VALUES(?,?,?)').run(fileId,'expired',attachment.length);
  db.prepare('INSERT INTO outbox VALUES(?,?,?)').run('queued','expired','sent');
  await writeFile(path.join(data,'uploads',fileId),attachment);
  await writeFile(path.join(data,'media','photo.webp'),'uploaded photo');
  await writeFile(path.join(data,'materials','document.pdf'),'private source material');
  db.prepare('INSERT INTO content VALUES(1,?)').run(JSON.stringify({projects:[{images:['media/photo.webp']}],materials:[{file:'materials/document.pdf'}]}));
  db.prepare('INSERT INTO admins VALUES(?,?)').run('test-admin','stored-password-hash');
  const nonce=Buffer.alloc(12,5),cipher=createCipheriv('aes-256-gcm',createHash('sha256').update(secret+'notifications-v6').digest(),nonce);
  const encrypted=Buffer.concat([cipher.update(JSON.stringify({smtpPassword:'TEST-ONLY-PASSWORD'})),cipher.final()]);
  db.prepare('INSERT INTO notification_settings VALUES(1,?)').run(Buffer.concat([nonce,cipher.getAuthTag(),encrypted]).toString('base64'));
  await assert.rejects(()=>purgeClosedLeads(db,data,null,now),/fresh verified backup/);
  const snapshot=await createBackup({db,dataDir:data,version:'13.0.0-test',environment:{NODE_ENV:'test',SMTP_PASSWORD:'LOCAL-TEST-ONLY',UNRELATED_TOKEN:'MUST-NOT-COPY'},now});
  assert.equal(snapshot.verified,true);assert.equal(snapshot.leads.length,10);
  assert.equal((await lstat(snapshot.directory)).mode&0o777,0o700);
  const manifest=JSON.parse(await readFile(path.join(snapshot.directory,'manifest.json'),'utf8'));
  for(const entry of manifest.files)assert.equal((await lstat(path.join(snapshot.directory,entry.path))).mode&0o777,0o600);
  assert.deepEqual(JSON.parse(await readFile(path.join(snapshot.directory,'runtime-config.json'),'utf8')),{NODE_ENV:'test',SMTP_PASSWORD:'LOCAL-TEST-ONLY'});
  const destination=path.join(temp,'restore-check');await restoreBackup(snapshot.directory,destination);
  restored=new DatabaseSync(path.join(destination,'facadepro.sqlite'),{readOnly:true});
  assert.equal(restored.prepare('SELECT COUNT(*) n FROM leads').get().n,10);
  assert.equal(restored.prepare('SELECT COUNT(*) n FROM outbox').get().n,1,'backup includes committed WAL data and relationships');
  assert.equal(restored.prepare('SELECT password FROM admins').get().password,'stored-password-hash');
  assert.deepEqual(await readFile(path.join(destination,'uploads',fileId)),attachment);
  assert.equal((await verifyBackup(destination)).verified,true,'restored secret decrypts saved notification configuration');
  restored.close();restored=null;
  await assert.rejects(()=>restoreBackup(snapshot.directory,destination),/already exists/);
  const tampered=path.join(temp,'tampered');await cp(snapshot.directory,tampered,{recursive:true});
  await writeFile(path.join(tampered,'uploads',fileId),'corrupted');
  await assert.rejects(()=>verifyBackup(tampered),/checksum mismatch/);
  await assert.rejects(()=>restoreBackup(tampered,path.join(temp,'must-not-exist')),/checksum mismatch/);
  await assert.rejects(()=>lstat(path.join(temp,'must-not-exist')),{code:'ENOENT'});
  const changed=await purgeClosedLeads(db,data,snapshot,now);
  assert.equal(changed.removedLeads,1);assert.equal(changed.removedFiles,1);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM leads').get().n,9,'active, contracts, future followup, new closure and reopened remain');
  await assert.rejects(()=>readFile(path.join(data,'uploads',fileId)),{code:'ENOENT'});
  assert.deepEqual(await readFile(path.join(snapshot.directory,'uploads',fileId)),attachment,'purged lead remains recoverable from verified backup');
  // A backup cannot authorize deletion of records changed after its snapshot.
  add('changed-after-backup','closed','2025-01-01T00:00:00.000Z');
  assert.equal((await purgeClosedLeads(db,data,snapshot,now)).removedLeads,0);
  // Missing files or symlinks must fail the next copy without pruning prior ones.
  const brokenId=randomUUID();db.prepare('INSERT INTO files VALUES(?,?,?)').run(brokenId,'new',3);
  await assert.rejects(()=>createBackup({db,dataDir:data,now}),/missing from backup/);
  db.prepare('DELETE FROM files WHERE id=?').run(brokenId);
  await symlink(path.join(data,'secret'),path.join(data,'media','linked.webp'));
  await assert.rejects(()=>createBackup({db,dataDir:data,now}),/regular files/);
  await rm(path.join(data,'media','linked.webp'));
  assert.ok((await readdir(path.join(data,'backups'))).includes(snapshot.name));
  assert.ok(!(await readdir(path.join(data,'backups'))).some(n=>n.startsWith('.incomplete')));
  const second=await createBackup({db,dataDir:data,now:new Date(now.getTime()+86400000)});
  const third=await createBackup({db,dataDir:data,now:new Date(now.getTime()+2*86400000)});
  const pruned=await pruneBackups(path.join(data,'backups'),{keep:2,now:new Date(now.getTime()+2*86400000),maxAgeDays:14});
  assert.deepEqual(pruned,[snapshot.name]);
  assert.equal((await verifyBackup(second.directory)).verified,true);assert.equal((await verifyBackup(third.directory)).verified,true);
  assert.equal(maintenanceConfig({NODE_ENV:'production'}).enabled,true);
  assert.equal(maintenanceConfig({NODE_ENV:'test'}).enabled,false);
  assert.throws(()=>maintenanceConfig({BACKUP_MAX_COPIES:'0'}));
  console.log('PASS v13 data safety: migration, active/contract preservation, closure age, reopen/future contact, verified-only retention, WAL snapshot, private modes, attachments/config restore, checksums, missing files, symlinks and backup pruning');
} finally {restored?.close();db?.close();await rm(temp,{recursive:true,force:true});}
