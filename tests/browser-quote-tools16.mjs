import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import path from 'node:path';

export async function verifyQuoteTools16({page,base,shots}) {
  const session=await (await page.request.get(base+'/api/admin/session')).json();
  assert.ok(session.csrf,'authenticated browser is required');
  const headers={Origin:base,'X-CSRF-Token':session.csrf};
  const createdResponse=await page.request.post(base+'/api/admin/leads',{headers,data:{name:'Экономика и шаблоны 16',company:'Тестовая компания',phone:'+7 999 016 16 16',email:'quote-tools16@example.test',city:'Владивосток',object:'Тест конструктора',services:['glazing'],source:'phone',assignee:session.username,idempotency:randomUUID(),allowDuplicate:true}});
  assert.equal(createdResponse.status(),201,await createdResponse.text());
  const created=await createdResponse.json(),leadBase='/api/admin/leads/'+created.id;
  const api=async(route,method='GET',data)=>{
    const response=await page.request.fetch(base+route,{method,headers,...(data?{data}:{})});
    assert.ok(response.ok(),method+' '+route+': '+await response.text());return response.json();
  };
  const pane=async name=>page.getByRole('tab',{name,exact:true}).click();
  const responseFor=(route,method)=>page.waitForResponse(response=>new URL(response.url()).pathname===route&&response.request().method()===method);
  const submit=async(selector,route,method)=>{
    const pending=responseFor(route,method);await page.locator(selector).click();return pending;
  };
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/admin/#leads/'+created.id,{waitUntil:'networkidle'});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#quote-template16-select:not([disabled])').waitFor({state:'attached'});
  await pane('КП');
  await page.locator('#lead-quote-builder>summary').click();
  const builder=page.locator('#lead-quote-build'),row=page.locator('.quote-build-item').first();
  await builder.locator('[name=title]').fill('Предложение из шаблона');
  await row.locator('[data-item-field=title]').fill('Монтаж витража <img src=x onerror=alert(1)>');
  await row.locator('[data-item-field=unit]').fill('м²');
  await row.locator('[data-item-field=quantity]').fill('1.5');
  await row.locator('[data-item-field=unitPrice]').fill('1000.11');
  await builder.locator('[name=taxMode]').selectOption('extra');
  await builder.locator('[name=taxRate]').fill('22');
  await builder.locator('[name=timeframe]').fill('20 рабочих дней');
  await builder.locator('[name=validUntil]').fill('2030-12-31');
  await builder.locator('[name=payment]').fill('Согласованный аванс');
  await builder.locator('[name=exclusions]').fill('Подготовка основания');
  await builder.locator('[name=customerNote]').fill('Уточним размеры');
  await page.locator('.quote-template16-editor>summary').click();
  const templateName='Витражи <script>alert(2)</script>',templateForm=page.locator('#quote-template16-form');
  await templateForm.locator('[name=name]').fill(templateName);
  await templateForm.locator('[name=serviceIds][value=glazing]').check();
  let response=await submit('#quote-template16-form button[type=submit]','/api/admin/quote-templates','POST');
  assert.equal(response.status(),201,await response.text());
  const first=await response.json(),template=first.template;
  await page.locator('#quote-template16-status').filter({hasText:'Шаблон сохранён'}).waitFor();
  assert.equal(template.document.validUntil,'','a template does not reuse an object expiry date');
  assert.equal(template.document.customer,undefined);assert.equal(template.document.company,undefined);
  assert.deepEqual(template.serviceIds,['glazing']);
  assert.equal((await api(leadBase+'/quotes')).quotes.length,0,'saving a template does not create a PDF');
  response=await submit('#quote-template16-form button[type=submit]','/api/admin/quote-templates','POST');
  assert.equal(response.status(),200,await response.text());
  const replay=await response.json();assert.equal(replay.template.id,template.id);assert.equal(replay.duplicate,true);
  await page.locator('#quote-template16-status').filter({hasText:'Шаблон сохранён'}).waitFor();
  assert.equal(await page.locator('.quote-templates16 script').count(),0,'template names remain literal text');
  assert.ok((await page.locator('#quote-template16-select option').allTextContents()).includes(templateName));
  await row.locator('[data-item-field=quantity]').fill('99');
  await page.locator('#quote-template16-apply').click();
  assert.equal(await row.locator('[data-item-field=quantity]').inputValue(),'1.5');
  assert.equal(await builder.locator('[name=validUntil]').inputValue(),'');
  assert.equal(await builder.locator('[name=taxRate]').inputValue(),'22');
  assert.equal(await builder.locator('[name=payment]').inputValue(),'Согласованный аванс');
  assert.equal(await builder.locator('script,img').count(),0,'template row text is escaped by the builder');
  assert.equal((await api(leadBase+'/quotes')).quotes.length,0,'apply only edits the draft');
  const updatedName='Витражи — согласованные условия';
  await templateForm.locator('[name=name]').fill(updatedName);
  await builder.locator('[name=payment]').fill('Оплата по этапам');
  response=await submit('#quote-template16-update','/api/admin/quote-templates/'+template.id,'PATCH');
  assert.equal(response.status(),200,await response.text());
  const updated=(await response.json()).template;assert.equal(updated.revision,2);assert.equal(updated.document.payment,'Оплата по этапам');
  await page.locator('#quote-template16-status').filter({hasText:'Шаблон обновлён'}).waitFor();
  const foreign=await api('/api/admin/quote-templates/'+template.id,'PATCH',{name:'Редакция другого сотрудника',serviceIds:['glazing'],document:{...updated.document,payment:'Иные условия'},revision:updated.revision,idempotency:randomUUID()});
  await templateForm.locator('[name=name]').fill('Мой несохранённый шаблон');
  response=await submit('#quote-template16-update','/api/admin/quote-templates/'+template.id,'PATCH');
  assert.equal(response.status(),409,'template concurrent update must be explicit');
  await page.locator('#quote-template16-status.error').waitFor();
  assert.equal(await templateForm.locator('[name=name]').inputValue(),'Мой несохранённый шаблон');
  assert.equal(await builder.locator('[name=payment]').inputValue(),'Оплата по этапам');
  await page.locator('#quote-template16-refresh').click();
  await page.locator('#quote-template16-status').filter({hasText:'Выберите шаблон заново'}).waitFor();
  assert.equal(await templateForm.locator('[name=name]').inputValue(),'Мой несохранённый шаблон','refresh preserves typed metadata');
  assert.equal(await page.locator('#quote-template16-update').isDisabled(),true,'refresh cannot silently adopt a foreign revision');
  await page.locator('#quote-template16-select').selectOption(template.id);
  assert.equal(await templateForm.locator('[name=name]').inputValue(),foreign.template.name);
  await templateForm.locator('[name=name]').fill('Название при смене фильтра');
  await page.locator('#quote-template16-filter').selectOption('windows');
  assert.equal(await page.locator('#quote-template16-select option[value="'+template.id+'"]').count(),0,'direction filters templates');
  assert.equal(await templateForm.locator('[name=name]').inputValue(),'Название при смене фильтра','filtering keeps unsaved template metadata');
  await page.locator('#quote-template16-filter').selectOption('glazing');
  await page.locator('#quote-template16-select').selectOption(template.id);
  await page.locator('#quote-template16-delete').click();
  assert.equal(await page.locator('#quote-template16-delete-confirm').isVisible(),true);
  response=await submit('#quote-template16-delete-yes','/api/admin/quote-templates/'+template.id,'DELETE');
  assert.equal(response.status(),200,await response.text());
  await page.locator('#quote-template16-status').filter({hasText:'Шаблон убран'}).waitFor();
  assert.ok(!(await api('/api/admin/quote-templates')).templates.some(item=>item.id===template.id));

  await pane('Экономика');
  await page.locator('#quote-costing16-form button[type=submit]:not([disabled])').waitFor({state:'attached'});
  const costing=page.locator('#quote-costing16-form'),costs=page.locator('.quote-costing16-item');
  await costing.locator('[name=revenue]').fill('4000.10');
  await page.locator('#quote-costing16-add').click();
  await costs.first().locator('[data-costing16-field=category]').selectOption('crew');
  await costs.first().locator('[data-costing16-field=title]').fill('Монтажники, человеко-дни');
  await costs.first().locator('[data-costing16-field=quantity]').fill('2.5');
  await costs.first().locator('[data-costing16-field=unitPrice]').fill('1000.10');
  await page.locator('#quote-costing16-add').click();
  await costs.last().locator('[data-costing16-field=category]').selectOption('materials');
  await costs.last().locator('[data-costing16-field=title]').fill('Расходные материалы <script>alert(3)</script>');
  await costs.last().locator('[data-costing16-field=quantity]').fill('1.25');
  await costs.last().locator('[data-costing16-field=unitPrice]').fill('399.99');
  assert.match(await costs.first().locator('[data-costing16-total]').innerText(),/2\s500,25/);
  assert.match(await costs.last().locator('[data-costing16-total]').innerText(),/499,99/);
  await costing.locator('[name=note]').fill('План по объекту <script>literal</script>');
  assert.equal(await costing.locator('[name=basisConfirmed]').isChecked(),false,'comparison basis is never assumed');
  assert.equal(await costing.evaluate(form=>form.checkValidity()),false,'tax comparison acknowledgement is required');
  await costing.locator('[name=basisConfirmed]').check();
  response=await submit('#quote-costing16-form button[type=submit]',leadBase+'/costing','PUT');
  assert.equal(response.status(),200,await response.text());
  const saved=await response.json();assert.equal(saved.totalCost,'3000.24');assert.equal(saved.plannedMargin,'999.86');assert.equal(saved.marginPercent,'25.00');
  assert.equal(saved.costs[0].lineTotal,'2500.25');assert.equal(saved.costs[1].lineTotal,'499.99');
  await page.locator('#quote-costing16-status').filter({hasText:'Расчёт сохранён'}).waitFor();
  assert.match(await page.locator('[data-costing16-margin]').innerText(),/999,86/);
  assert.equal(await page.locator('.quote-costing16 script').count(),0);
  assert.equal((await api(leadBase+'/quotes')).quotes.length,0,'internal costing never creates or publishes a quote');
  await api(leadBase+'/costing','PUT',{revision:saved.revision,basis:'comparable',revenue:'8000',costs:saved.costs.map(({lineTotal,...item})=>item),note:'Другая редакция расчёта'});
  await costing.locator('[name=note]').fill('Мой несохранённый расчёт');
  assert.equal(await page.locator('#quote-costing16-result').isVisible(),false,'changed input hides stale result');
  response=await submit('#quote-costing16-form button[type=submit]',leadBase+'/costing','PUT');
  assert.equal(response.status(),409,'costing prevents a concurrent overwrite');
  await page.locator('#quote-costing16-status.error').waitFor();
  assert.equal(await costing.locator('[name=note]').inputValue(),'Мой несохранённый расчёт');
  assert.equal(await costing.locator('[name=revenue]').inputValue(),'4000.10');
  await page.locator('#quote-costing16-reload').click();
  assert.equal(await page.locator('#quote-costing16-reload-confirm').isVisible(),true,'reloading a draft is explicit');
  await page.locator('#quote-costing16-reload-no').click();
  assert.equal(await costing.locator('[name=note]').inputValue(),'Мой несохранённый расчёт');
  await page.locator('#quote-costing16-reload').click();
  await page.locator('#quote-costing16-reload-yes').click();
  await page.locator('#quote-costing16-status').filter({hasText:'Сохранённый расчёт загружен'}).waitFor();
  assert.equal(await costing.locator('[name=revenue]').inputValue(),'8000.00');
  assert.equal(await costing.locator('[name=basisConfirmed]').isChecked(),false);
  await costing.locator('[name=revenue]').fill('1000');await costing.locator('[name=basisConfirmed]').check();
  response=await submit('#quote-costing16-form button[type=submit]',leadBase+'/costing','PUT');
  assert.equal(response.status(),200,await response.text());
  const negative=await response.json();assert.equal(negative.plannedMargin,'-2000.24');assert.equal(negative.marginPercent,'-200.02');
  await page.locator('#quote-costing16-result:not([hidden])').waitFor();
  assert.equal(await page.locator('[data-costing16-margin]').getAttribute('class'),'quote-costing16-negative');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'costing fits 390px');
  await page.screenshot({path:path.join(shots,'quote-tools-v16-costing-mobile.png'),fullPage:true});
  await costing.locator('[name=revenue]').fill('');
  response=await submit('#quote-costing16-form button[type=submit]',leadBase+'/costing','PUT');
  assert.equal(response.status(),200,await response.text());const costsOnly=await response.json();assert.equal(costsOnly.plannedMargin,null);assert.equal(costsOnly.marginPercent,null);
  await page.locator('#quote-costing16-result-note').filter({hasText:'Укажите цену'}).waitFor();
  assert.equal(await page.locator('[data-costing16-margin]').innerText(),'—');
  assert.equal((await api(leadBase+'/quotes')).quotes.length,0);
  for(const width of [320,1440]){
    await page.setViewportSize({width,height:width===1440?1000:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'costing fits '+width);
    await page.screenshot({path:path.join(shots,'quote-tools-v16-costing-'+width+'.png'),fullPage:true});
    await pane('КП');assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'template tools fit '+width);await pane('Экономика');
  }
  // Reload establishes a clean form baseline; adding a cost row must trigger the shared draft guard.
  await page.reload({waitUntil:'networkidle'});await pane('Экономика');
  await page.locator('#quote-costing16-form button[type=submit]:not([disabled])').waitFor({state:'attached'});
  await page.locator('#quote-costing16-add').click();
  await page.locator('#lead-dirty-status').filter({hasText:'несохранённые'}).waitFor();
  await page.locator('#back-leads').click();await page.locator('#confirm-dialog').waitFor({state:'visible'});await page.locator('#confirm-cancel').click();
  assert.equal(await page.locator('.quote-costing16-item').count(),3,'draft row stays after cancelled navigation');
  await page.locator('#back-leads').click();await page.locator('#confirm-dialog').waitFor({state:'visible'});await page.locator('#confirm-yes').click();
  await page.locator('#new-manual-lead').waitFor();
  await page.request.delete(base+leadBase,{headers});
  console.log('PASS v16 quote tools: template create/retry/apply/update/archive, concurrent template and costing edits, exact costs/margin/negative/empty revenue, explicit tax basis, private draft guard, 320/390/1440 widths');
}
